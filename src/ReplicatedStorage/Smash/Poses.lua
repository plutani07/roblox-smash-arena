local ZERO = { 0, 0, 0, 0, 0, 0 }

local function smooth(a)
	return a * a * (3 - 2 * a)
end

-- Returns { joint = {rx, ry, rz, px, py, pz} } for the given anim at u (0..1)
function Poses.Sample(animName, u)
	local frames = A[animName]
	if not frames then return nil end
	u = math.clamp(u, 0, 1)
	local k0, k1 = frames[1], frames[#frames]
	for i = 1, #frames - 1 do
		if u >= frames[i][1] and u <= frames[i + 1][1] then
			k0, k1 = frames[i], frames[i + 1]
			break
		end
	end
	local span = k1[1] - k0[1]
	local a = span > 0 and smooth((u - k0[1]) / span) or 1
	local out = {}
	for joint in pairs(Poses.Joints) do
		local p0 = k0[2][joint]
		local p1 = k1[2][joint]
		if p0 or p1 then
			p0 = p0 or ZERO
			p1 = p1 or ZERO
			local v = {}
			for c = 1, 6 do
				v[c] = (p0[c] or 0) + ((p1[c] or 0) - (p0[c] or 0)) * a
			end
			out[joint] = v
		end
	end
	return out
end

return Poses
